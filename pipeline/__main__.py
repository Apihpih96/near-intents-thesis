"""One command for everything.

  python -m pipeline all       # fetch live data, then build (needs internet)
  python -m pipeline build     # rebuild from the committed snapshots in data/raw/ (offline)
  python -m pipeline fetch     # only refresh data/raw/
  python -m pipeline model     # only re-run the bear/base/bull model after editing model/assumptions.yaml
"""
import json
import sys
from pathlib import Path

from . import clean, fetch, metrics, model

ROOT = Path(__file__).resolve().parent.parent
PROCESSED = ROOT / "data" / "processed"
DASH_DATA = ROOT / "docs" / "data.js"


def export_dashboard():
    bundle = {n: json.loads((PROCESSED / f"{n}.json").read_text()) for n in ("daily", "metrics", "model")}
    bundle["manifest"] = json.loads((ROOT / "data" / "raw" / "manifest.json").read_text())
    DASH_DATA.write_text("// generated by `python -m pipeline`; do not edit\nwindow.THESIS_DATA = "
                         + json.dumps(bundle, separators=(",", ":")) + ";\n")
    print(f"  docs/data.js: {DASH_DATA.stat().st_size // 1024} KB")


def build():
    d = clean.build()
    m = metrics.build(d)
    model.build(m)
    export_dashboard()


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "build"
    if cmd == "fetch":
        fetch.fetch_all()
    elif cmd == "build":
        build()
    elif cmd == "all":
        fetch.fetch_all()
        build()
    elif cmd == "model":
        m = json.loads((PROCESSED / "metrics.json").read_text())
        model.build(m)
        export_dashboard()
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
